"""Compile the shared message catalog for the browser, TypeScript and ESP32."""
from pathlib import Path
import argparse
import json
import re

ROOT=Path(__file__).resolve().parents[1]
LANGUAGES=['ko','zh-CN','ja','en','de']
NAMES=['한국어','简体中文','日本語','English','Deutsch']

def outputs():
    messages=json.loads((ROOT/'locales/messages.json').read_text(encoding='utf-8'))
    for key,row in messages.items():
        assert set(row)==set(LANGUAGES)-{'ko'} and all(row.values()),key
        # Translations must preserve printf arguments and their types/order.
        fmt=lambda s: re.findall(r'%(?!%)(?:\.[0-9]+)?[dfs]',s)
        assert all(fmt(key)==fmt(text) for text in row.values()),key
    data={'languages':LANGUAGES,'names':NAMES,'messages':messages}
    js='// Generated by tools/generate_locales.py; edit locales/messages.json.\n'
    web=js+'globalThis.QuotamonI18n = '+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n'
    ts=js+'export const languages = '+json.dumps(LANGUAGES)+' as const\n'
    source='\n'.join((ROOT/p).read_text(encoding='utf-8') for p in ['native/ui.cpp','firmware/main/main.cpp'])
    literals=set(re.findall(r'"([^"\\]*(?:\\.[^"\\]*)*)"',source))
    dynamic={'요금제 미확인','리셋 후 확인 대기','사용량 원천 미연결','사용량 확인 불가',
             '비선택 계정 · 수치 전송 없음','Copilot 조회 실패','Copilot SDK · 단위 확인 필요',
             'Copilot 사용량 원천 미연결','시각 미확인','미확인'}
    for path in (ROOT/'orca-integration/src').glob('*.ts'):
        dynamic.update(re.findall(r"'([^'\n]*[가-힣][^'\n]*)'",path.read_text(encoding='utf-8')))
    selected={k:v for k,v in messages.items() if k in literals or k in dynamic}
    q=lambda s: json.dumps(s,ensure_ascii=False)
    lines=['// Generated by tools/generate_locales.py; edit locales/messages.json.',
           '#pragma once','#include <cstring>','#include <string>',
           'namespace monitor::i18n {',
           'inline constexpr const char* languages[]={'+','.join(map(q,LANGUAGES))+'};',
           'inline constexpr const char* names[]={'+','.join(map(q,NAMES))+'};',
           'inline int index(const std::string& language) {',
           '  for(int i=0;i<5;i++) { if(language==languages[i])return i; }', '  return 0;}',
           'inline bool valid(const std::string& language) {',
           '  for(const auto* code:languages) { if(language==code)return true; }', '  return false;}',
           'inline constexpr const char* messages[][5]={']
    for key,row in selected.items():
        lines.append('  {'+','.join(q(key if code=='ko' else row[code]) for code in LANGUAGES)+'},')
    lines+=['};','inline const char* text(const char* key,const std::string& language) {',
            '  const int column=index(language);if(!column)return key;',
            '  for(const auto& row:messages) { if(std::strcmp(key,row[0])==0)return row[column]; }', '  return key;',
            '}','}']
    return {'portable/web/locales.js':web,'orca-integration/src/languages.ts':ts,
            'native/generated/translations.h':'\n'.join(lines)+'\n'}

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for name,value in outputs().items():
        path=ROOT/name
        if args.check:assert path.read_text(encoding='utf-8')==value,f'{name} is stale'
        else:path.write_text(value,encoding='utf-8')
    print('Shared locale catalog: '+('verified' if args.check else 'generated'))
