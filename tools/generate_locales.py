"""Compile the shared message catalog for the browser, TypeScript and ESP32."""
from pathlib import Path
import argparse
import json
import re
from bidi import algorithm as bidi

ROOT=Path(__file__).resolve().parents[1]
LANGUAGES={
    'ko':'한국어', 'zh-CN':'简体中文', 'ja':'日本語', 'en':'English', 'de':'Deutsch',
    'hi':'हिन्दी', 'es':'Español', 'ar':'العربية', 'fr':'Français', 'bn':'বাংলা',
    'pt':'Português', 'id':'Bahasa Indonesia', 'ur':'اردو', 'ru':'Русский',
    'pcm':'Naijá', 'ar-EG':'العربية المصرية',
}
RTL={'ar','ur','ar-EG'}
SHAPED_WORDS={
    'hi':re.compile(r'[\u0900-\u097f\u200c\u200d]+'),
    'bn':re.compile(r'[\u0980-\u09ff\u200c\u200d]+'),
    **{code:re.compile(r'[\u0620-\u063f\u0641-\u065f\u0670-\u06d3\u06d5-\u06ed\u06fa-\u06ff\u200c\u200d]+') for code in RTL},
}
FORMAT=re.compile(r'%(?!%)(?:\.[0-9]+)?[dfs]')

def lcd_messages(messages):
    source='\n'.join((ROOT/p).read_text(encoding='utf-8') for p in ['native/ui.cpp','firmware/main/main.cpp'])
    literals=set(re.findall(r'"([^"\\]*(?:\\.[^"\\]*)*)"',source))
    dynamic={'요금제 미확인','리셋 후 확인 대기','사용량 원천 미연결','사용량 확인 불가',
             '비선택 계정 · 수치 전송 없음','Copilot 조회 실패','Copilot SDK · 단위 확인 필요',
             'Copilot 사용량 원천 미연결','시각 미확인','미확인'}
    for path in (ROOT/'orca-integration/src').glob('*.ts'):
        dynamic.update(re.findall(r"'([^'\n]*[가-힣][^'\n]*)'",path.read_text(encoding='utf-8')))
    return {k:v for k,v in messages.items() if k in literals or k in dynamic}

def rtl_display(text):
    # LVGL draws the prepared string from left to right. Keep format tokens and
    # Latin unit abbreviations together when reordering the right-to-left text.
    formats=[]
    def protect(match):
        formats.append(match[0])
        return f'QPRINTF{len(formats)-1}Q'
    text=FORMAT.sub(protect,text)
    storage=bidi.get_empty_storage()
    storage.update(base_level=1,base_dir='R')
    bidi.get_embedding_levels(text,storage)
    for char in storage['chars']:
        if 0xe000<=ord(char['ch'])<0xf900:
            char.update(type='R',orig='R')
    bidi.explicit_embed_and_overrides(storage)
    bidi.resolve_weak_types(storage)
    bidi.resolve_neutral_types(storage,False)
    bidi.resolve_implicit_levels(storage,False)
    bidi.reorder_resolved_levels(storage,False)
    bidi.apply_mirroring(storage,False)
    visual=''.join(char['ch'] for char in storage['chars'])
    order=[int(match) for match in re.findall(r'QPRINTF(\d+)Q',visual)]
    assert order==list(range(len(formats))),text
    return re.sub(r'QPRINTF(\d+)Q',lambda m:formats[int(m[1])],visual)

def lcd_catalog(messages):
    selected=lcd_messages(messages)
    words={}
    def display(text,code):
        if code not in SHAPED_WORDS:
            return text
        def glyph(match):
            key=('ar' if code=='ar-EG' else code,match[0])
            return words.setdefault(key,chr(0xe000+len(words)))
        prepared=SHAPED_WORDS[code].sub(glyph,text)
        return rtl_display(prepared) if code in RTL else prepared
    names=[display(name,code) for code,name in LANGUAGES.items()]
    rows=[[key if code=='ko' else display(row[code],code) for code in LANGUAGES] for key,row in selected.items()]
    assert len(words)<=0x1900, 'LCD glyphs exceed the private-use range'
    return names,rows,words

def outputs():
    messages=json.loads((ROOT/'locales/messages.json').read_text(encoding='utf-8'))
    for key,row in messages.items():
        assert set(row)==set(LANGUAGES)-{'ko'} and all(row.values()),key
        assert all(FORMAT.findall(key)==FORMAT.findall(text) for text in row.values()),key
    names,rows,_=lcd_catalog(messages)
    data={'languages':list(LANGUAGES),'names':list(LANGUAGES.values()),'rtl':sorted(RTL),'messages':messages}
    js='// Generated by tools/generate_locales.py; edit locales/messages.json.\n'
    web=js+'globalThis.QuotamonI18n = '+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n'
    ts=js+'export const languages = '+json.dumps(list(LANGUAGES))+' as const\n'
    ts+='export const languageNames = '+json.dumps(LANGUAGES,ensure_ascii=False)+' as const\n'
    q=lambda s: json.dumps(s,ensure_ascii=False)
    lines=['// Generated by tools/generate_locales.py; edit locales/messages.json.',
           '#pragma once','#include <cstring>','#include <string>',
           'namespace monitor::i18n {',
           'inline constexpr const char* languages[]={'+','.join(map(q,LANGUAGES))+'};',
           'inline constexpr const char* names[]={'+','.join(map(q,names))+'};',
           'inline constexpr const char* options='+q('\n'.join(names))+';',
           'inline constexpr int languageCount=sizeof(languages)/sizeof(languages[0]);',
           'inline int index(const std::string& language) {',
           '  for(int i=0;i<languageCount;i++) { if(language==languages[i])return i; }', '  return 0;}',
           'inline bool valid(const std::string& language) {',
           '  for(const auto* code:languages) { if(language==code)return true; }', '  return false;}',
           'inline constexpr const char* messages[][languageCount]={']
    for row in rows:
        lines.append('  {'+','.join(map(q,row))+'},')
    lines+=['};','inline const char* text(const char* key,const std::string& language) {',
            '  const int column=index(language);if(!column)return key;',
            '  for(const auto& row:messages) { if(std::strcmp(key,row[0])==0)return row[column]; }', '  return key;',
            '}','}']
    return {'portable/web/locales.js':web,'orca-integration/src/languages.ts':ts,
            'native/generated/translations.h':'\n'.join(lines)+'\n'}

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for name,value in outputs().items():
        path=ROOT/name
        if args.check:assert path.read_text(encoding='utf-8')==value,f'{name} is stale'
        else:path.write_text(value,encoding='utf-8')
    print('Shared locale catalog: '+('verified' if args.check else 'generated'))
